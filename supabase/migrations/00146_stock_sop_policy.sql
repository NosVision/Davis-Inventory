## 1. วินัยเรื่องเวลาและการวางแผน (PA & PR)

**การนับสต็อก — ระบบ Davis AI**
พนักงานบาร์ต้องนับสต็อกจริงและบันทึกข้อมูลลงระบบให้เสร็จ **ก่อน 05:00 น. ทุกวัน**

**การวางแผนสต็อก (PA) และการส่งใบสั่งซื้อ (PR)**
พนักงานต้องวางแผนสต็อกเองและส่งใบ PR ไปยัง HQ ภายในเวลาทำงานเท่านั้น

**ข้อห้ามที่ต้องปฏิบัติอย่างเคร่งครัด**
- ห้ามทำใบ PR ตอนเข้างาน
- ห้ามสั่งของในช่วงที่ออดิทกำลังปฏิบัติหน้าที่

**บทลงโทษ:** ทำใบ PR ผิดเวลา หรือไม่มีแผนการจัดการสต็อก — ระงับสิทธิ์การเบิกเหล้าทันที

**กรณีฉุกเฉิน (ของหมดระหว่างกะ):** หากของหมดเพราะวางแผนผิดพลาด ต้องติดต่อขออนุมัติจากเจ้านายโดยตรงเท่านั้น (ออดิทไม่มีหน้าที่รับผิดชอบความเสียหายที่เกิดจากการวางแผนพลาด)

## 2. มาตรฐานการจัดการเหล้า ENT และ Pre-batch

**เหล้า ENT (รหัส A-04):** ขวดทุกใบที่นำมาเติม ต้องติดสติกเกอร์สีเขียวทุกครั้ง — ไม่มีข้อยกเว้น

**Pre-batch (รหัส A-05):** ทุกขวด Pre-batch ต้องแปะโพสอิทข้างขวด โดยระบุ
1. ชื่อประเภทเหล้าที่ใช้ผสม
2. ปริมาณที่เหลืออยู่ในปัจจุบัน (มล.)

## 3. การส่งเหล้าหมดอายุคืนคลังกลาง

ส่งคืน **ทุกวันอังคาร ภายในเวลา 18:00 – 18:20 น. เท่านั้น**
ส่งช้ากว่าเวลาที่กำหนด — ปรับ 100 บาท / วัน

> หมายเหตุ: ค่าปรับนี้ไม่นับเป็นคะแนนความผิดสะสม และไม่ส่งผลต่อการออกใบเตือนหัวหน้าบาร์

## 4. ระบบนับคะแนนความผิดรายเดือน

**หลักการนับคะแนน**
- ความผิดที่มีการหักเงินทุกกรณี นับเป็น 1 ความผิด ต่อ 1 ครั้ง
- แต่ละเดือนมีโควตาสูงสุด 12 ครั้ง สำหรับทุกร้าน
- ค่าปรับการส่งเหล้าหมดอายุช้า (EXP-01) ไม่นับรวมในคะแนนสะสมนี้

**เกณฑ์การออกใบเตือน**
- หากร้านใดมีความผิดสะสมเกิน 7 ครั้งต่อเดือน หัวหน้าบาร์จะได้รับใบเตือนทันที
- ใบเตือนจะถูกบันทึกในประวัติและส่งต่อให้ผู้บริหารรับทราบ

