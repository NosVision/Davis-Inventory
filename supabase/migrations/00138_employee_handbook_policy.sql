# 6. การประเมินผลการปฏิบัติงาน

## หัวข้อการประเมิน

1. ปฏิบัติตามคำสั่งของหัวหน้าอย่างเคร่งครัด
2. ความขยันขันแข็งในการทำงาน ไม่พักนาน ไม่หายจากหน้างาน
3. แต่งกายสุภาพเรียบร้อย ทั้งใบหน้า ผม และสภาพร่างกาย
4. ดูแลลูกค้าได้ดี ควบคุมอารมณ์ และยิ้มแย้มแจ่มใส
5. ดูแลความสะอาดและข้าวของเครื่องใช้ในการทำงาน
6. ความผิดพลาดหน้างาน การสั่งออร์เดอร์ และการทำตาม Service Standard ของร้าน
7. ความเร็วและความกระตือรือร้นในการทำงาน
8. การพัฒนาและการเรียนรู้งาน
9. การสื่อสารกับหัวหน้าและเพื่อนร่วมงาน
10. การแก้ปัญหาเฉพาะหน้าและการแก้ปัญหาเบื้องต้น
11. ความซื่อสัตย์ในการทำงาน ไม่ขอทิปจากลูกค้า
12. การทำงานร่วมกับผู้อื่นและการทำงานเป็นทีม
13. การช่วยเหลือและดูแลความสะอาดของร้าน
14. การปฏิบัติตามกฎระเบียบของบริษัทอย่างเคร่งครัด
15. ความรับผิดชอบต่อเวลา ไม่ขาด ลา หรือมาสายบ่อย

## วัตถุประสงค์ของการประเมิน

- เพื่อติดตามและพัฒนาศักยภาพของพนักงาน
- เพื่อใช้เป็นเกณฑ์ในการพิจารณาผลตอบแทน

## ผลของการประเมิน

ผลการประเมินจะมีผลต่อการปรับเงิน Service Charge และผลตอบแทนอื่นๆ ตามที่บริษัทกำหนด

