ระเบียบในส่วนนี้จัดทำขึ้นเพื่อคุ้มครองการดำเนินธุรกิจ ความปลอดภัยของพนักงานและลูกค้า และเพื่อให้สอดคล้องกับกฎหมายแรงงานไทย พนักงานทุกท่านต้องปฏิบัติตามเช่นเดียวกับระเบียบในส่วนที่ 1–8

