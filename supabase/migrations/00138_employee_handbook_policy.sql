- หนังสือตักเตือนมีอายุ 12 เดือนนับจากวันที่ออก
- พนักงานมีสิทธิชี้แจงข้อเท็จจริงก่อนการลงโทษทุกครั้ง
- **ความผิดร้ายแรง** เช่น ทุจริต ลักทรัพย์ ทะเลาะวิวาทหรือทำร้ายร่างกายในที่ทำงาน เมาสุราหรือใช้สารเสพติดจนเสียงาน จงใจทำให้บริษัทเสียหาย หรือละทิ้งหน้าที่ 3 วันทำงานติดต่อกันโดยไม่มีเหตุอันสมควร บริษัทมีสิทธิเลิกจ้างได้ทันทีโดยไม่ต้องจ่ายค่าชดเชย ตามมาตรา 119 แห่งพระราชบัญญัติคุ้มครองแรงงาน

# 11. นโยบายแอลกอฮอล์และสารเสพติด

- ห้ามดื่มสุราหรือเครื่องดื่มแอลกอฮอล์ขณะปฏิบัติงาน และห้ามมาทำงานในสภาพมึนเมาโดยเด็ดขาด
- ห้ามครอบครอง ใช้ หรือซื้อขายยาเสพติดทุกชนิดภายในสถานที่ทำงานโดยเด็ดขาด
- การชิมเครื่องดื่มเพื่อตรวจสอบคุณภาพทำได้เฉพาะเมื่อได้รับอนุมัติจากผู้จัดการ และต้องบ้วนทิ้ง ไม่กลืน
- บริษัทอาจขอให้พนักงานเข้ารับการตรวจหาสารเสพติดตามความเหมาะสมและตามที่กฎหมายอนุญาต
- **การฝ่าฝืนถือเป็นความผิดร้ายแรง** บริษัทมีสิทธิเลิกจ้างได้ทันที และดำเนินคดีตามกฎหมายหากเกี่ยวข้องกับสารเสพติด

# 12. จรรยาบรรณและการป้องกันการล่วงละเมิด

- ปฏิบัติต่อเพื่อนร่วมงาน ลูกค้า และคู่ค้า ด้วยความเคารพและสุภาพเสมอ
- ห้ามการล่วงละเมิดหรือคุกคามทางเพศทุกรูปแบบ ทั้งทางวาจา การกระทำ การสัมผัส และข้อความ ตามมาตรา 16 แห่งพระราชบัญญัติคุ้มครองแรงงาน
- ห้ามเลือกปฏิบัติหรือกลั่นแกล้งด้วยเหตุแห่งเพศ ศาสนา เชื้อชาติ อายุ หรือความแตกต่างส่วนบุคคล
- ห้ามรับสินบนหรือผลประโยชน์ใดๆ ที่ขัดต่อหน้าที่และผลประโยชน์ของบริษัท
- **ช่องทางร้องเรียน:** แจ้งหัวหน้างานหรือฝ่ายทรัพยากรบุคคลโดยตรง บริษัทจะเก็บข้อมูลผู้ร้องเรียนเป็นความลับ และจะไม่ตอบโต้ผู้ที่ร้องเรียนโดยสุจริต

## 12.1 เวลาทำงาน กะ และการทำงานล่วงเวลา

- เวลาทำงานปกติไม่เกิน 8 ชั่วโมงต่อวัน และไม่เกิน 48 ชั่วโมงต่อสัปดาห์ ตามที่กฎหมายกำหนด
- เวลาพักไม่น้อยกว่า 1 ชั่วโมง หลังจากทำงานติดต่อกันไม่เกิน 5 ชั่วโมง
- วันหยุดประจำสัปดาห์อย่างน้อย 1 วันต่อสัปดาห์
- ตารางกะกำหนดโดยผู้จัดการแต่ละสาขา พนักงานต้องเข้างานตรงตามกะที่ได้รับมอบหมาย
- การลงเวลาเข้า-ออกงานต้องเป็นความจริงทุกครั้ง การลงเวลาแทนผู้อื่นถือเป็นความผิดร้ายแรง

**การทำงานล่วงเวลา (OT)** ต้องได้รับความยินยอมจากพนักงานและการอนุมัติจากหัวหน้างานก่อน โดยจ่ายตามอัตราที่กฎหมายกำหนด

| ลักษณะการทำงาน | อัตราค่าจ้าง |
| --- | --- |
| ล่วงเวลาในวันทำงานปกติ | 1.5 เท่า |
| ทำงานในวันหยุด (ในเวลาปกติ) | 2 เท่า |
| ล่วงเวลาในวันหยุด | 3 เท่า |

# 13. การทดลองงาน

- พนักงานเข้าใหม่มีระยะเวลาทดลองงาน 119 วัน
- ระหว่างทดลองงาน บริษัทจะประเมินผลตามหัวข้อในข้อ 6
- หากผลการทดลองงานไม่ผ่านเกณฑ์ บริษัทอาจเลิกจ้างได้ภายในระยะเวลาดังกล่าว
- เมื่อผ่านการทดลองงาน พนักงานจะได้รับสิทธิและสวัสดิการเต็มรูปแบบตามนโยบายบริษัท

# 14. การลาออกและการบอกกล่าวล่วงหน้า

- พนักงานที่ประสงค์จะลาออกต้องยื่นหนังสือลาออกล่วงหน้าอย่างน้อย 30 วัน
- ต้องส่งมอบงาน คืนทรัพย์สินของบริษัท และเคลียร์ภาระผูกพันทั้งหมดให้เรียบร้อยก่อนวันทำงานวันสุดท้าย
- บริษัทจะจ่ายค่าจ้างส่วนที่เหลือในรอบการจ่ายเงินเดือนตามปกติ
- การลาออกโดยไม่บอกกล่าวล่วงหน้าตามกำหนด อาจมีผลต่อการออกหนังสือรับรองการทำงาน

# 15. ระเบียบการแต่งกายและบุคลิกภาพ

- แต่งกายตามเครื่องแบบของแต่ละตำแหน่ง สะอาดและเรียบร้อยตลอดเวลาปฏิบัติงาน
- ผม เล็บ และสุขอนามัยส่วนบุคคลต้องเรียบร้อยและเหมาะสมกับงานบริการ
- ติดป้ายชื่อขณะปฏิบัติงานทุกครั้ง
- สวมรองเท้าหุ้มส้นหรือปิดหน้าเท้าเพื่อความปลอดภัยในการทำงาน
- เครื่องประดับและกลิ่นน้ำหอมแต่พอเหมาะ ไม่รบกวนการให้บริการหรือเพื่อนร่วมงาน

# 16. การคุ้มครองข้อมูลส่วนบุคคล (PDPA)

- บริษัทเก็บรวบรวมและใช้ข้อมูลส่วนบุคคลของพนักงานเพื่อวัตถุประสงค์ด้านการจ้างงาน การจ่ายเงินเดือน สวัสดิการ และการปฏิบัติตามกฎหมายเท่านั้น
- บริษัทเก็บรักษาข้อมูลตามระยะเวลาที่จำเป็นและตามที่กฎหมายกำหนด
- บริษัทจะไม่เปิดเผยข้อมูลส่วนบุคคลแก่บุคคลภายนอกโดยไม่จำเป็น หรือโดยไม่ได้รับความยินยอม เว้นแต่เป็นไปตามกฎหมาย
- พนักงานมีสิทธิขอเข้าถึง ขอแก้ไข หรือขอลบข้อมูลส่วนบุคคลของตนตามที่กฎหมายกำหนด
- **ติดต่อเรื่องข้อมูลส่วนบุคคล:** ฝ่ายทรัพยากรบุคคล — เป็นไปตามพระราชบัญญัติคุ้มครองข้อมูลส่วนบุคคล พ.ศ. 2562

# 17. การรักษาความลับและทรัพย์สินของบริษัท

- ห้ามเปิดเผยข้อมูลความลับของบริษัท เช่น สูตรอาหารและเครื่องดื่ม ข้อมูลยอดขาย ข้อมูลลูกค้า และข้อมูลพนักงาน แก่บุคคลภายนอก
- ทรัพย์สินของบริษัท (อุปกรณ์ เครื่องมือ เครื่องแบบ) ใช้เพื่อการปฏิบัติงานเท่านั้น และต้องส่งคืนเมื่อพ้นสภาพการเป็นพนักงาน
- ห้ามนำทรัพย์สิน วัตถุดิบ หรือสินค้าออกจากร้านโดยไม่ได้รับอนุญาต
- หน้าที่ในการรักษาความลับยังคงมีผลต่อเนื่องแม้พ้นสภาพการเป็นพนักงานแล้ว

# 18. ความปลอดภัยในการทำงานและการแจ้งอุบัติเหตุ

- ปฏิบัติตามมาตรการความปลอดภัยและสุขอนามัยของบริษัทอย่างเคร่งครัด
- รายงานอุบัติเหตุ การบาดเจ็บ หรือสภาพการทำงานที่ไม่ปลอดภัยต่อหัวหน้างานทันที
- ทราบตำแหน่งของอุปกรณ์ปฐมพยาบาล ถังดับเพลิง และเส้นทางหนีไฟ
- กรณีบาดเจ็บจากการทำงาน บริษัทจะดำเนินการตามสิทธิกองทุนเงินทดแทนและประกันสังคม
- ระเบียบนี้สอดคล้องกับพระราชบัญญัติความปลอดภัย อาชีวอนามัยและสภาพแวดล้อมในการทำงาน พ.ศ. 2554

